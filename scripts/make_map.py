"""Generate web/land.js (world land outline as one SVG path) from Natural Earth via world-atlas.

    npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
    python3 scripts/make_map.py package/land-110m.json > web/land.js

Projection is equirectangular cropped to latitudes 84°N to 58°S: x = lon + 180, y = 84 - lat,
so the app can place a point with the same two lines of arithmetic. Natural Earth is public domain.
"""

import json
import sys

TOP, BOTTOM = 84, -58


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring(indexes, arcs):
    pts = []
    for i in indexes:
        seg = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        pts.extend(seg if not pts else seg[1:])
    return pts


def main(path):
    topo = json.load(open(path))
    arcs = decode_arcs(topo)
    out = []
    for geom in topo["objects"]["land"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        for poly in polys:
            for r in poly:
                raw = ring(r, arcs)
                if len(raw) < 3 or max(lat for _, lat in raw) < BOTTOM:
                    continue  # Antarctica and anything else wholly below the crop
                pts = [(lon + 180, TOP - lat) for lon, lat in raw]
                d, last = [], None
                for x, y in pts:
                    p = f"{x:.1f} {min(y, TOP - BOTTOM):.1f}"
                    if p != last:
                        d.append(p)
                        last = p
                if len(d) >= 3:
                    out.append("M" + "L".join(d) + "Z")
    print("/* Natural Earth land (public domain) via world-atlas 2.0.2; generated by scripts/make_map.py */")
    print(f"window.WP_LAND = {{ width: 360, height: {TOP - BOTTOM}, top: {TOP}, d: {json.dumps(''.join(out))} }};")


if __name__ == "__main__":
    main(sys.argv[1])
